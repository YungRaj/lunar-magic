    #[test]
    fn recovered_object_tables_have_exact_compacted_shapes_and_order() {
        assert_eq!(STANDARD_OBJECT_TILESET_REQUIREMENTS.len(), 41);
        assert_eq!(STANDARD_OBJECT_GFX_REQUIREMENTS.len(), 105);
        assert_eq!(EXTENDED_OBJECT_TILESET_REQUIREMENTS.len(), 271);
        assert_eq!(EXTENDED_OBJECT_GFX_REQUIREMENTS.len(), 134);
        for table in [
            STANDARD_OBJECT_TILESET_REQUIREMENTS
                .iter()
                .map(|&(scope, command, _)| (scope, command))
                .collect::<Vec<_>>(),
            STANDARD_OBJECT_GFX_REQUIREMENTS
                .iter()
                .map(|&(scope, command, _, _)| (scope, command))
                .collect::<Vec<_>>(),
        ] {
            assert!(
                table
                    .windows(2)
                    .all(|rows| rows[0].0 != rows[1].0 || rows[0].1 <= rows[1].1)
            );
            let mut scopes = table.iter().map(|&(scope, _)| scope).collect::<Vec<_>>();
            scopes.dedup();
            assert!(scopes.windows(2).all(|rows| rows[0] != rows[1]));
        }
        assert!(
            EXTENDED_OBJECT_TILESET_REQUIREMENTS
                .windows(2)
                .all(|rows| rows[0].0 <= rows[1].0)
        );
        assert!(
            EXTENDED_OBJECT_GFX_REQUIREMENTS
                .windows(2)
                .all(|rows| rows[0].0 <= rows[1].0)
        );
    }

