/// Matches Lunar Magic's built-in standard-sprite graphics filter.
#[must_use]
pub(crate) fn standard_sprite_is_graphics_compatible(
    sprite: u8,
    graphics_mode: u8,
    sprite_files: [usize; 4],
) -> bool {
    // The original accepts sprite $8C before consulting its built-in requirement row.
    if sprite == 0x8c {
        return true;
    }
    let mut has_requirements = false;
    for &(candidate, required_mode, required_sp3, required_sp4) in STANDARD_SPRITE_REQUIREMENTS {
        if candidate != sprite {
            continue;
        }
        has_requirements = true;
        if matches_byte(required_mode, graphics_mode)
            && matches_file(required_sp3, sprite_files[2])
            && matches_file(required_sp4, sprite_files[3])
        {
            return true;
        }
    }
    !has_requirements
}

const fn matches_byte(requirement: u8, actual: u8) -> bool {
    requirement == 0xff || requirement == actual
}

fn matches_file(requirement: u8, actual: usize) -> bool {
    requirement == 0xff || usize::from(requirement) == actual
}

