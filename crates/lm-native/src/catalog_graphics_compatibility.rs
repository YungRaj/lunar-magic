/// Matches Lunar Magic's standard-object cell-2 compatibility filter.
#[must_use]
pub(crate) fn standard_object_is_graphics_compatible(
    command: u8,
    family: u8,
    object_tileset: u8,
    foreground_files: [usize; 4],
) -> bool {
    let scope_matches = |scope: u8| scope == 0xff || scope == family;
    let mut has_tileset_requirements = false;
    let tileset_matches = STANDARD_OBJECT_TILESET_REQUIREMENTS
        .iter()
        .filter(|&&(scope, candidate, _)| scope_matches(scope) && candidate == command)
        .any(|&(_, _, required_tileset)| {
            has_tileset_requirements = true;
            required_tileset == object_tileset
        });
    if has_tileset_requirements && !tileset_matches {
        return false;
    }

    let mut has_gfx_requirements = false;
    let gfx_matches = STANDARD_OBJECT_GFX_REQUIREMENTS
        .iter()
        .filter(|&&(scope, candidate, _, _)| scope_matches(scope) && candidate == command)
        .any(|&(_, _, required_bg1, required_fg3)| {
            has_gfx_requirements = true;
            matches_file(required_bg1, foreground_files[2])
                && matches_file(required_fg3, foreground_files[3])
        });
    !has_gfx_requirements || gfx_matches
}

/// Matches Lunar Magic's extended-object cell-2 compatibility filter.
#[must_use]
pub(crate) fn extended_object_is_graphics_compatible(
    selector: u8,
    object_tileset: u8,
    foreground_files: [usize; 4],
) -> bool {
    // Selector $7F switches to dedicated tables in tilesets 4, 5, and D.
    if selector == 0x7f && matches!(object_tileset, 0x04 | 0x05 | 0x0d) {
        return foreground_files[3] == 0x07;
    }

    let mut has_tileset_requirements = false;
    let tileset_matches = EXTENDED_OBJECT_TILESET_REQUIREMENTS
        .iter()
        .filter(|&&(candidate, _)| candidate == selector)
        .any(|&(_, required_tileset)| {
            has_tileset_requirements = true;
            required_tileset == object_tileset
        });
    if has_tileset_requirements && !tileset_matches {
        return false;
    }

    let mut has_gfx_requirements = false;
    let gfx_matches = EXTENDED_OBJECT_GFX_REQUIREMENTS
        .iter()
        .filter(|&&(candidate, _, _)| candidate == selector)
        .any(|&(_, required_bg1, required_fg3)| {
            has_gfx_requirements = true;
            matches_file(required_bg1, foreground_files[2])
                && matches_file(required_fg3, foreground_files[3])
        });
    !has_gfx_requirements || gfx_matches
}

