/// Matches Lunar Magic's built-in standard-sprite graphics filter.
#[must_use]
pub(crate) fn standard_sprite_is_graphics_compatible(
    sprite: u8,
    graphics_mode: u8,
    sprite_files: [usize; 4],
) -> bool {
    // The original accepts sprite $8C before consulting its built-in requirement row.
    if sprite == 0x8c {
        return true;
    }
    let mut has_requirements = false;
    for &(candidate, required_mode, required_sp3, required_sp4) in STANDARD_SPRITE_REQUIREMENTS {
        if candidate != sprite {
            continue;
        }
        has_requirements = true;
        if matches_byte(required_mode, graphics_mode)
            && matches_file(required_sp3, sprite_files[2])
            && matches_file(required_sp4, sprite_files[3])
        {
            return true;
        }
    }
    !has_requirements
}

const fn matches_byte(requirement: u8, actual: u8) -> bool {
    requirement == 0xff || requirement == actual
}

fn matches_file(requirement: u8, actual: usize) -> bool {
    requirement == 0xff || usize::from(requirement) == actual
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recovered_table_has_exact_compacted_shape_and_boundaries() {
        assert_eq!(STANDARD_SPRITE_REQUIREMENTS.len(), 178);
        assert_eq!(
            STANDARD_SPRITE_REQUIREMENTS.first(),
            Some(&(0x0d, 0xff, 0xff, 0x02))
        );
        assert_eq!(
            STANDARD_SPRITE_REQUIREMENTS.last(),
            Some(&(0xe6, 0xff, 0xff, 0x03))
        );
        assert!(
            STANDARD_SPRITE_REQUIREMENTS
                .windows(2)
                .all(|rows| rows[0].0 <= rows[1].0)
        );
    }

    #[test]
    fn predicate_matches_wildcards_alternatives_modes_and_the_8c_exception() {
        assert!(standard_sprite_is_graphics_compatible(
            0x00,
            0,
            [0, 1, 2, 3]
        ));
        assert!(standard_sprite_is_graphics_compatible(
            0x0d,
            0,
            [0, 1, 7, 2]
        ));
        assert!(!standard_sprite_is_graphics_compatible(
            0x0d,
            0,
            [0, 1, 7, 3]
        ));
        assert!(standard_sprite_is_graphics_compatible(
            0x1b,
            0,
            [0, 1, 7, 4]
        ));
        assert!(standard_sprite_is_graphics_compatible(
            0x1b,
            0,
            [0, 1, 7, 0x0e]
        ));
        assert!(!standard_sprite_is_graphics_compatible(
            0x1b,
            0,
            [0, 1, 7, 5]
        ));
        assert!(standard_sprite_is_graphics_compatible(
            0xa5,
            2,
            [0, 1, 7, 5]
        ));
        assert!(!standard_sprite_is_graphics_compatible(
            0xa5,
            3,
            [0, 1, 7, 5]
        ));
        assert!(standard_sprite_is_graphics_compatible(
            0x8c,
            0,
            [0, 1, 7, 7]
        ));
    }
}
